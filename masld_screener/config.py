# -*- coding: utf-8 -*-
"""
config.py — 集中管理 masld_screener 的所有筛选阈值。

用户只需修改本文件即可调整筛选严格程度，无需改动 masld_screener.py 主逻辑。
所有阈值均基于 MASLD（代谢功能障碍相关脂肪性肝病）已知活性/临床阶段
小分子（见 reference_molecules.py）的统计范围设定，可作为起点按需微调。
"""

# ---------------------------------------------------------------------------
# Phase 1: 去重与标准化
# ---------------------------------------------------------------------------
# 基于 canonical SMILES 去重（RDKit 规范化后的唯一 SMILES）
DEDUP_METHOD = "canonical_smiles"


# ---------------------------------------------------------------------------
# Phase 2: 理化性质筛选阈值（基于 MASLD 已知活性分子统计）
# ---------------------------------------------------------------------------
# 每个键对应一个 (最小值, 最大值) 区间，分子属性落在区间内（含端点）方为通过。
# 说明：
#   MW   分子量 g/mol            —— 口服小分子常见范围
#   LogP 脂水分配系数 (Crippen)  —— 适度亲脂性有利于膜通透与组织分布
#   TPSA 拓扑极性表面积 Å²       —— 影响膜通透（通常 < 140 利于口服）
#   HBD  氢键供体数             —— Lipinski 规则上限 5
#   HBA  氢键受体数             —— Lipinski 规则上限 10
#   RotB 可旋转键数             —— 柔性，过多不利成药
#   Lipinski_violations Lipinski 五规则违规数（MW>500/LogP>5/HBD>5/HBA>10）
PHYS_CHEM_FILTERS = {
    "MW":   (300, 600),       # 分子量 g/mol
    "LogP": (2.0, 6.0),       # 脂水分配系数
    "TPSA": (50, 150),        # 拓扑极性表面积 Å²
    "HBD":  (0, 5),           # 氢键供体数
    "HBA":  (0, 10),          # 氢键受体数
    "RotB": (0, 10),          # 可旋转键数
    "Lipinski_violations": (0, 1),  # Lipinski 违规数
}


# ---------------------------------------------------------------------------
# Phase 3: 相似性搜索参数
# ---------------------------------------------------------------------------
SIMILARITY_THRESHOLD = 0.3    # Tanimoto 最小保留阈值（MaxTC >= 该值保留）
FINGERPRINT_RADIUS = 2        # Morgan/ECFP4 半径
FINGERPRINT_BITS = 2048       # 指纹位数


# ---------------------------------------------------------------------------
# Phase 4: ADMET 毒性筛选条件
# ---------------------------------------------------------------------------
# 基于 admet-ai 输出的端点（具体列名以 admet-ai 实际输出为准，脚本会动态检测）。
# 取值含义：
#   False   —— 该端点应为“阴性/安全”（如 hERG 非抑制、Ames 非致突变、无肝毒性）
#   ">0.3"  —— 该端点数值应大于给定阈值（如口服生物利用度 > 30%）
#   ">-5"   —— 该端点数值应大于给定阈值（如水溶性 LogS > -5）
TOXICITY_FILTERS = {
    "herg_inhibition": False,       # hERG 非抑制
    "ames_mutagenicity": False,     # Ames 非致突变
    "hepatotoxicity": False,        # 无肝毒性
    "oral_bioavailability": ">0.3", # 口服生物利用度 > 30%
    "aqueous_solubility": ">-5",    # 水溶性 LogS > -5
}


# ---------------------------------------------------------------------------
# Phase 5: 综合评分权重（三者之和应为 1.0）
# ---------------------------------------------------------------------------
SCORE_WEIGHTS = {
    "similarity": 0.4,   # 与已知活性分子的相似性
    "physchem":   0.3,   # 理化合规度
    "toxicity":   0.3,   # 毒性安全性
}
